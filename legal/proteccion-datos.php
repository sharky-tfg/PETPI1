    <h5>1. Introducción</h5>
    <p>En PetAdopta nos tomamos muy en serio la protección de tus datos personales. Esta página complementa nuestra Política de Privacidad y detalla aspectos específicos sobre el tratamiento de datos en nuestra plataforma.</p>
    
    <h5>2. Delegado de Protección de Datos</h5>
    <p>Hemos designado un Delegado de Protección de Datos (DPD) que puedes contactar en: <a href="mailto:dpo@petadopta.org">dpo@petadopta.org</a></p>
    
    <h5>3. Datos especialmente protegidos</h5>
    <p>No solicitamos ni procesamos datos especialmente protegidos (salud, ideología, etc.) salvo que sea estrictamente necesario para el proceso de adopción y con tu consentimiento explícito.</p>
    
    <h5>4. Transferencias internacionales</h5>
    <p>No realizamos transferencias de datos a países fuera del Espacio Económico Europeo. En caso de hacerlo, garantizamos niveles de protección adecuados.</p>
    
    <h5>5. Decisiones automatizadas</h5>
    <p>No tomamos decisiones automatizadas que puedan afectarte legalmente sin intervención humana. El proceso de adopción siempre es revisado por personas.</p>
    
    <h5>6. Seguridad de los datos</h5>
    <p>Aplicamos medidas de seguridad como:</p>
    <ul>
      <li>Cifrado de comunicaciones mediante HTTPS.</li>
      <li>Almacenamiento seguro de contraseñas con hash.</li>
      <li>Acceso restringido a datos personales.</li>
      <li>Copias de seguridad periódicas.</li>
    </ul>
    
    <h5>7. Notificación de brechas de seguridad</h5>
    <p>En caso de violación de seguridad que afecte tus datos, te notificaremos sin dilación indebida cuando sea relevante.</p>
    
    <h5>8. Conservación de datos</h5>
    <p>Conservamos tus datos mientras mantengas una cuenta activa. Una vez cerrada, se bloquearán durante 5 años por obligaciones legales, tras lo cual se eliminarán definitivamente.</p>
    
    <h5>9. Reclamaciones</h5>
    <p>Si consideras que tus derechos no han sido atendidos, puedes presentar una reclamación ante la Agencia Española de Protección de Datos (<a href="https://www.aepd.es" target="_blank">www.aepd.es</a>).</p>
    
    <h5>10. Ejercicio de derechos</h5>
    <p>Para ejercer tus derechos ARCO (Acceso, Rectificación, Cancelación, Oposición), utiliza nuestro formulario específico o envía un correo a <a href="mailto:dpo@petadopta.org">dpo@petadopta.org</a> con el asunto "Protección de Datos".</p>
    
